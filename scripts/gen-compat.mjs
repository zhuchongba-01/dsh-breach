/**
 * 把 README 里的兼容数字从「手填」改成「跑一次生成」。
 * 读当前安装的宿主和补丁结算结果，重写 <!-- compat:begin --> 与 <!-- compat:end --> 之间的内容。
 * 用法：node scripts/gen-compat.mjs
 */
import fs from "node:fs";
import path from "node:path";
import * as core from "../lib/core.js";
import { classifyHostVersion } from "../lib/host-range.js";
import { currentSurface } from "../lib/host.js";
import { hostAiBase } from "../lib/index.js";

const BEGIN = "<!-- compat:begin -->";
const END = "<!-- compat:end -->";

async function counts() {
  const aiBase = hostAiBase();
  if (!aiBase) return { total: 0, applied: 0, skipped: 0, na: 0, err: "没定位到宿主" };
  const status = await core.patchStatus(aiBase);
  const rows = Object.values(status || {});
  return {
    total: core.ALL_PATCHES.filter((p) => core.patchAppliesHere(p)).length,
    applied: rows.filter((s) => s === "applied" || s === "already").length,
    skipped: rows.filter((s) => s === "skipped" || s === "missing_file").length,
    na: core.ALL_PATCHES.filter((p) => !core.patchAppliesHere(p)).length,
    err: "",
  };
}

async function block(lang) {
  const version = (() => {
    try {
      const base = hostAiBase();
      if (!base) return "";
      const appDir = path.dirname(path.dirname(path.dirname(base)));
      return String(JSON.parse(fs.readFileSync(path.join(appDir, "package.json"), "utf8")).version || "");
    } catch { return ""; }
  })();
  const c = await counts();
  const info = classifyHostVersion(version);
  const zh = lang === "zh";
  const head = zh
    ? `| 项 | 值 | 状态 |`
    : `| Item | Value | Status |`;
  const sep = `|---|---|---|`;
  const surface = currentSurface();
  const row1 = zh
    ? `| 宿主 \`${version || "?"}\` · ${surface} | ${c.total} 项结算，${c.applied} 生效 / ${c.skipped} 跳过 · ${c.na} 项本机不适用 | ${info.level === "verified" ? "已验证" : "未验证"} |`
    : `| Host \`${version || "?"}\` · ${surface} | ${c.total} settled, ${c.applied} applied / ${c.skipped} skipped · ${c.na} n/a here | ${info.level === "verified" ? "verified" : "unverified"} |`;
  const note = zh
    ? `\n> 由 \`node scripts/gen-compat.mjs\` 生成，别手改数字。\n`
    : `\n> Generated by \`node scripts/gen-compat.mjs\`; do not hand-edit the numbers.\n`;
  return [BEGIN, head, sep, row1, note.trim(), END].join("\n");
}

let wrote = 0;
for (const [file, lang] of [["README.md", "zh"], ["README.en.md", "en"]]) {
  const fp = path.join(process.cwd(), file);
  if (!fs.existsSync(fp)) continue;
  const text = fs.readFileSync(fp, "utf8");
  const body = await block(lang);
  let next;
  if (text.includes(BEGIN) && text.includes(END)) {
    next = text.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), body);
  } else {
    continue;
  }
  if (next !== text) {
    fs.writeFileSync(fp, next, "utf8");
    wrote += 1;
  }
}
console.log(`gen-compat: ${wrote} 个 README 片段已更新`);
